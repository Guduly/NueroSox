"""Sanity targets, observation table and timing for tests/replay_check.py (real recordings; NOT validation)."""
import os

def wins(msgs): return [m for m in msgs if m.get("type") == "window"]
def f(v, n=2): return "—" if v is None else ("%.*f" % (n, v) if isinstance(v, (int, float)) and not isinstance(v, bool) else str(v))

def targets(res, thr):
    """Return list of (name, passed, detail) for the §8.3 behaviour checks."""
    out = []; W = {r: wins(v[1]) for r, v in res.items()}
    thr_ok = lambda w: not w.get("area_elev")
    w1 = W["ecg_ppg1"]
    out.append(("ecg_ppg1: no 'walking'", all(w["act"] != "walking" for w in w1), [w["act"] for w in w1]))
    out.append(("ecg_ppg1: no region at/above elevated threshold", all(thr_ok(w) for w in w1), [max(w["area"] or [0]) for w in w1]))
    for r in ("ecg_ppg2", "ecg_ppg3"):
        bad = [w["k"] for w in W[r] if w.get("usable") and w["act"] == "walking"]
        out.append(("%s: no 'walking' in usable windows" % r, not bad, bad))
    wa = W["achilles1"]
    out.append(("achilles1: all uncertain / ecg_only / partial", all(w["act"] == "uncertain" and w["act_basis"] == "ecg_only" and w["area_q"] == "partial" for w in wa),
                [(w["act"], w["act_basis"], w["area_q"]) for w in wa]))
    ws = W["stress"]; m = lambda L: [w["strain"] for w in L if w["strain"] is not None]
    s_stress, s_rest = m(ws), m(w1)
    mean = lambda a: sum(a) / len(a) if a else float("nan")
    out.append(("stress: runs; mean strain higher than ecg_ppg1", len(ws) > 0 and mean(s_stress) > mean(s_rest), (round(mean(s_stress), 3), round(mean(s_rest), 3))))
    return out

def run(res, outdir):
    os.makedirs(outdir, exist_ok=True)
    thr = None; L = ["# Observations on real recordings (NOT validation)", "",
        "Single subject, no activity labels, no recording is known to contain walking.  The tables show what the model output for",
        "each window.  `act` is a model label, not the subject's activity.  Generated by tests/replay_check.py.", ""]
    for r, (mo, mn, to, tn) in res.items():
        L += ["## %s" % r, "", "| k | HR | p_card | mot_f | mot_ratio | act | conf | strain | max area | area_q | reason |", "|---|---|---|---|---|---|---|---|---|---|---|"]
        for w in wins(mn):
            L.append("| %d | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s |" % (w["k"], f(w.get("hr_ecg"), 0), f(w.get("p_card")), f(w.get("mot_f")), f(w.get("mot_ratio")),
                     w["act"], f(w["act_conf"]), f(w["strain"]), f(max(w["area"]) if w.get("area") else None, 3), w["area_q"], w["act_reason"].replace("|", "/")))
        L.append("")
    ok = True; L += ["## Sanity targets (behaviour checks, not validation)", ""]
    print("\nSanity targets:")
    for name, passed, detail in targets(res, thr):
        ok &= passed; print("  %s  %s   %s" % ("PASS" if passed else "FAIL", name, "" if passed else detail)); L.append("- %s **%s**" % (name, "pass" if passed else "FAIL: %s" % (detail,)))
    L += ["", "## Timing (laptop, whole subprocess incl. interpreter start)", "", "| recording | windows | original s | new s | extra ms / window |", "|---|---|---|---|---|"]
    for r, (mo, mn, to, tn) in res.items():
        n = len(wins(mn)); L.append("| %s | %d | %.2f | %.2f | %.0f |" % (r, n, to, tn, 1000 * (tn - to) / max(1, n)))
    open(os.path.join(outdir, "observations.md"), "w").write("\n".join(L) + "\n")
    print("  observations written to", os.path.join(outdir, "observations.md"))
    return 0 if ok else 2
